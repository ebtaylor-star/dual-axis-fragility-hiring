best_steps_per_feature = pd.DataFrame(index=rejected.index, columns=FEATURE_STEPS.keys(), dtype=float)

for feat, steps in FEATURE_STEPS.items():
    remaining = rejected.copy()
    for n_steps in range(1, len(steps)):
        if remaining.empty:
            break
        current_idx = remaining[feat].apply(lambda v: steps.index(v) if v in steps else None)
        movable = remaining[current_idx.notna() & (current_idx + n_steps < len(steps))]
        if movable.empty:
            continue

        trial_batch = movable[feature_cols].copy()
        new_vals = [steps[steps.index(v) + n_steps] for v in movable[feat]]
        trial_batch[feat] = new_vals

        preds = clf.predict(trial_batch)
        flipped_idx = movable.index[preds == 1]

        best_steps_per_feature.loc[flipped_idx, feat] = n_steps
