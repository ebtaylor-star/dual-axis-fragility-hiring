def compute_shap_summary(model, X_data, feature_names, title, filename):
    explainer = shap.TreeExplainer(model)
    shap_values = explainer.shap_values(X_data)

    # Handle both older list-per-class and 3D array return shapes from SHAP
    if isinstance(shap_values, list):
        values_for_hire_class = shap_values[1]
    elif getattr(shap_values, 'ndim', 0) == 3:
        values_for_hire_class = shap_values[:, :, 1]
    else:
        values_for_hire_class = shap_values

        cleaned_feature_names = [f.replace('_', ' ').title() for f in feature_names]

    plt.figure(figsize=(10, 6))
    shap.summary_plot(
        values_for_hire_class,
        X_data,
        feature_names=cleaned_feature_names,
        show=False
    )
    plt.title(title, fontweight='bold', fontsize=12, pad=15)
    plt.tight_layout()
    plt.savefig(filename, dpi=300, bbox_inches='tight')
    plt.show()

